import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * Generates components/sal/icon-data.ts from the Society's icon set,
 * brand/icons/icon-*.svg (Lucide, ISC, redrawn at a 1.5 px line with square
 * ends; decided Oct 30, 2026). Each icon becomes the list of its shapes, so
 * the Icon component draws it inline in the text's color.
 *
 *   bun scripts/icons.ts          # write it
 *   bun scripts/icons.ts --check  # fail if it is stale
 */
export const iconsDir = join(
  import.meta.dirname,
  "..",
  "..",
  "..",
  "brand",
  "icons"
);
export const iconDataPath = join(
  import.meta.dirname,
  "..",
  "components",
  "sal",
  "icon-data.ts"
);

const SHAPE = /<(path|circle|line|polyline|polygon|rect)\s([^>]*?)\s*\/>/g;
const ATTRIBUTE = /([a-z-]+)="([^"]*)"/g;
const ICON_FILE = /^icon-(.+)\.svg$/;

/** The shapes of one icon file, as [tag, attributes]. */
export const parseIcon = (svg: string) =>
  [...svg.matchAll(SHAPE)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries(
      [...(attrs ?? "").matchAll(ATTRIBUTE)].map(([, k, v]) => [k, v])
    ),
  ]) as [string, Record<string, string>][];

export const renderIconData = async () => {
  const files = (await readdir(iconsDir))
    .filter((f) => ICON_FILE.test(f))
    .sort();
  const entries = await Promise.all(
    files.map(async (file) => {
      const name = file.replace(ICON_FILE, "$1");
      const shapes = parseIcon(await readFile(join(iconsDir, file), "utf8"));
      return `  "${name}": ${JSON.stringify(shapes)},`;
    })
  );
  return `// Generated by scripts/icons.ts from brand/icons. Do not edit.

export const iconData = {
${entries.join("\n")}
} as const satisfies Record<string, readonly (readonly [string, Record<string, string>])[]>;

export type IconName = keyof typeof iconData;
`;
};

if (import.meta.main) {
  const data = await renderIconData();
  if (process.argv.includes("--check")) {
    const current = await readFile(iconDataPath, "utf8").catch(() => "");
    if (current !== data) {
      console.error(
        `${iconDataPath} is stale. Run \`bun run --cwd packages/design-system icons\`.`
      );
      process.exit(1);
    }
  } else {
    await writeFile(iconDataPath, data);
  }
}
