import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * Generates the CSS for the brand's own token file, brand/tokens.json
 * (binding), into two places:
 *
 * - packages/design-system/styles/tokens.css: the palette as `--sal-*`, the
 *   spacing scale, radii and strokes, the type families, and the color roles
 *   for light and dark mode. The platform's type utilities live in
 *   styles/globals.css and follow the same values.
 * - brand/tokens.css: the same tokens for documents and posts (load it before
 *   brand/components/bundle.css), with the fonts and one class per type style.
 *
 *   bun scripts/tokens.ts          # write both
 *   bun scripts/tokens.ts --check  # fail if either is stale
 */
interface Themed {
  dark: string;
  light: string;
}

interface Token<T = string> {
  name: string;
  value: T;
}

interface TypeStyle {
  fontSize: string;
  fontWeight: number;
  letterSpacing?: string;
  lineHeight?: number;
  name: string;
}

export interface BrandTokens {
  color: { tokens: Token<string | Themed>[] };
  radius: { tokens: Token[] };
  spacing: { tokens: Token[] };
  stroke: { tokens: Token[] };
  type: {
    families: Record<string, string>;
    fonts: { family: string; file: string; style: string; weight: string }[];
    groups: { family: string; name: string; styles: TypeStyle[] }[];
  };
}

const REFERENCE = /^\{([a-z0-9-]+)\}$/;

const reference = (value: string) => {
  const match = REFERENCE.exec(value);
  if (!match) {
    throw new Error(`Role values must reference a palette color: ${value}`);
  }
  return match[1] ?? "";
};

export const splitColors = (tokens: BrandTokens) => {
  const palette: Record<string, string> = {};
  const roles: Record<string, Themed> = {};
  for (const token of tokens.color.tokens) {
    if (typeof token.value === "string") {
      palette[token.name] = token.value;
    } else {
      roles[token.name] = token.value;
    }
  }
  return { palette, roles };
};

/** Spacing, radii and strokes: one list, in the file's order. */
export const sizeTokens = (tokens: BrandTokens) => [
  ...tokens.spacing.tokens,
  ...tokens.radius.tokens,
  ...tokens.stroke.tokens,
];

const roleLines = (
  roles: Record<string, Themed>,
  theme: keyof Themed,
  prefix: string
) =>
  Object.entries(roles).map(
    ([role, value]) =>
      `  --${role}: var(--${prefix}${reference(value[theme])});`
  );

const HEADER =
  "/* Generated by packages/design-system/scripts/tokens.ts from brand/tokens.json. Do not edit. */";

/** packages/design-system/styles/tokens.css */
export const renderTokens = (tokens: BrandTokens) => {
  const { palette, roles } = splitColors(tokens);
  const lines = [
    HEADER,
    ":root {",
    ...Object.entries(palette).map(
      ([name, value]) => `  --sal-${name}: ${value};`
    ),
    ...sizeTokens(tokens).map(
      (token) => `  --sal-${token.name}: ${token.value};`
    ),
    ...Object.entries(tokens.type.families).map(
      ([name, value]) => `  --sal-font-${name}: ${value};`
    ),
    "}",
    "",
    "/* Light mode, and paper that stays light in dark mode (certificates, letters, printouts). */",
    ":root,",
    '[data-theme="light"] {',
    ...roleLines(roles, "light", "sal-"),
    "}",
    "",
    "/* Dark mode: ink for the whole page, rose in place of crimson. */",
    '[data-theme="dark"] {',
    ...roleLines(roles, "dark", "sal-"),
    "}",
    "",
  ];
  return lines.join("\n");
};

const GOOGLE_FONTS =
  "https://fonts.googleapis.com/css2?family=Ubuntu:ital,wght@0,300;0,400;0,500;0,700;1,300;1,400&family=Ubuntu+Mono:wght@400;700&family=Literata:wght@400;500&display=swap";

const UPPERCASE = new Set(["label", "print-label"]);

const typeClass = (style: TypeStyle, family: string) => {
  const rules = [
    `font-family: var(--font-${family})`,
    `font-size: ${style.fontSize}`,
    `font-weight: ${style.fontWeight}`,
    ...(style.lineHeight === undefined
      ? []
      : [`line-height: ${style.lineHeight}`]),
    ...(style.letterSpacing ? [`letter-spacing: ${style.letterSpacing}`] : []),
    ...(UPPERCASE.has(style.name) ? ["text-transform: uppercase"] : []),
    ...(family === "arabic" ? ["direction: rtl"] : []),
  ];
  return `.${style.name} { ${rules.join("; ")}; }`;
};

/** brand/tokens.css: documents and posts, with the fonts and type classes. */
export const renderBrandTokens = (tokens: BrandTokens) => {
  const { palette, roles } = splitColors(tokens);
  return [
    "/* AUIB Society of Arts and Letters, design tokens. Generated from tokens.json by packages/design-system/scripts/tokens.ts; edit that file, not this one. */",
    `@import url('${GOOGLE_FONTS}');`,
    "/* Ubuntu Arabic is not on Google Fonts; it ships in fonts/ (Ubuntu Font License 1.0). */",
    ...tokens.type.fonts.map(
      (font) =>
        `@font-face { font-family: "${font.family}"; src: url("${font.file}") format("woff2"); font-weight: ${font.weight}; font-style: ${font.style}; font-display: swap; }`
    ),
    ":root {",
    ...Object.entries(palette).map(([name, value]) => `  --${name}: ${value};`),
    ...sizeTokens(tokens).map((token) => `  --${token.name}: ${token.value};`),
    ...Object.entries(tokens.type.families).map(
      ([name, value]) => `  --font-${name}: ${value};`
    ),
    "}",
    ':root, [data-theme="light"] {',
    ...roleLines(roles, "light", ""),
    "}",
    '[data-theme="dark"] {',
    ...roleLines(roles, "dark", ""),
    "}",
    ...tokens.type.groups.flatMap((group) =>
      group.styles.map((style) => typeClass(style, group.family))
    ),
    "",
  ].join("\n");
};

export const brandTokensPath = join(
  import.meta.dirname,
  "..",
  "..",
  "..",
  "brand",
  "tokens.json"
);

if (import.meta.main) {
  const tokens = JSON.parse(
    await readFile(brandTokensPath, "utf8")
  ) as BrandTokens;
  const targets = [
    {
      css: renderTokens(tokens),
      path: join(import.meta.dirname, "..", "styles", "tokens.css"),
    },
    {
      css: renderBrandTokens(tokens),
      path: join(brandTokensPath, "..", "tokens.css"),
    },
  ];

  if (process.argv.includes("--check")) {
    const current = await Promise.all(
      targets.map((target) => readFile(target.path, "utf8").catch(() => ""))
    );
    const stale = targets.filter((target, i) => current[i] !== target.css);
    for (const target of stale) {
      console.error(
        `${target.path} is stale. Run \`bun run --cwd packages/design-system tokens\`.`
      );
    }
    if (stale.length > 0) {
      process.exit(1);
    }
  } else {
    await Promise.all(
      targets.map((target) => writeFile(target.path, target.css))
    );
  }
}
