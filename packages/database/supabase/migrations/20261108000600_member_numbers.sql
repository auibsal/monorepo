-- Member and guest numbers (decisions §6 table, §10 "Numbering now").
-- One five-digit series for everyone, assigned once and never reused or
-- changed. Before joining opens they are reassigned: the founding team
-- first in seat order (President 00001, Vice President, General Secretary,
-- Editor-in-Chief, Managing Editor, Director of Media, Next Stop host),
-- then everyone else by the date they joined. Then they are locked.
--
-- The fault: viewing a card ran `insert … on conflict do nothing`, and an
-- identity column takes its next value before the conflict is found, so
-- every view used up a number (the series jumped 12 → 109 → … → 405).

-- 1. Renumber, in one pass, by seat and then by join date.
alter table membership.cards alter column number set generated by default;

update membership.cards set number = -number;

with seats(role, seat) as (
  values ('president', 1), ('vice_president', 2), ('general_secretary', 3),
    ('eic', 4), ('managing_editor', 5), ('media_director', 6), ('next_stop_host', 7)
),
seat_of as (
  select r.user_id, min(s.seat) as seat
  from access.role_assignments r
  join seats s on s.role = r.role
  where r.scope_type = 'global'
    and r.starts_at <= now() and (r.ends_at is null or r.ends_at > now())
  group by r.user_id
),
ordered as (
  select c.user_id,
    row_number() over (order by so.seat nulls last, u.created_at, c.issued_at) as n
  from membership.cards c
  join auth.users u on u.id = c.user_id
  left join seat_of so on so.user_id = c.user_id
)
update membership.cards c set number = o.n
from ordered o where o.user_id = c.user_id;

do $$
declare
  next_number integer;
begin
  select coalesce(max(number), 0) + 1 into next_number from membership.cards;
  execute format(
    'alter table membership.cards alter column number restart with %s', next_number
  );
end;
$$;

alter table membership.cards alter column number set generated always;

-- 2. Locked: a number never changes once given.
create function private.lock_card_number()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.number is distinct from old.number then
    raise exception using errcode = '42501', message = 'number_locked',
      hint = 'Member and guest numbers are assigned once and never changed.';
  end if;
  return new;
end;
$$;

revoke all on function private.lock_card_number() from public, anon, authenticated;

create trigger lock_number
  before update of number on membership.cards
  for each row execute function private.lock_card_number();

-- 3. Viewing a card no longer uses up a number: a card is made only when
-- there isn't one.
create or replace function private.my_card()
returns table (number integer, code text, secret text, issued_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if private.membership_kind((select auth.uid())) is null then
    raise exception 'not_a_member' using errcode = '42501';
  end if;
  if not exists (
    select 1 from membership.cards c where c.user_id = (select auth.uid())
  ) then
    insert into membership.cards (user_id) values ((select auth.uid()))
    on conflict (user_id) do nothing;
  end if;
  return query
    select c.number, c.code, encode(c.secret, 'hex'), c.issued_at
    from membership.cards c where c.user_id = (select auth.uid());
end;
$$;

create or replace function private.reissue_card()
returns table (number integer, code text, secret text, issued_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if private.membership_kind((select auth.uid())) is null then
    raise exception 'not_a_member' using errcode = '42501';
  end if;
  -- A new code and secret, the same number.
  update membership.cards
  set code = encode(extensions.gen_random_bytes(10), 'hex'),
      secret = extensions.gen_random_bytes(20),
      issued_at = now()
  where user_id = (select auth.uid());
  if not found then
    insert into membership.cards (user_id) values ((select auth.uid()))
    on conflict (user_id) do nothing;
  end if;
  return query
    select c.number, c.code, encode(c.secret, 'hex'), c.issued_at
    from membership.cards c where c.user_id = (select auth.uid());
end;
$$;

-- 4. Saved Google Wallet passes show the new numbers (the outbox's
-- wallet.renumber patches each pass).
select private.enqueue('wallet.renumber', jsonb_build_object('code', w.code, 'number', c.number))
from membership.wallet_passes w
join membership.cards c on c.code = w.code
where w.state is distinct from 'expired';
