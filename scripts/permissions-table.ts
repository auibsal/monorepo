/**
 * The permissions table for the Leadership Handbook and the quarterly
 * access review (decisions.md, The site: Tools and settings), generated
 * from the code's role bundles (apps/web/lib/rbac, the mirror of the
 * database that rbac.test.ts keeps honest). `bun scripts/permissions-table.ts`
 * writes docs/platform/permissions.md; `--check` fails when it is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { roleKeys, roles } from "../apps/web/lib/rbac/roles";

const OUT = join(import.meta.dir, "..", "docs/platform/permissions.md");

/** Permissions that reach personal data: two-step sign-in from Nov 22, 2026. */
const PERSONAL = new Set([
  "audit.read",
  "concerns.handle",
  "events.checkin",
  "elections.manage",
  "events.manage",
  "forms.handle",
  "journal.identity.view",
  "mailing.read",
  "members.manage",
  "members.register",
  "members.verify",
  "partners.lead",
  "partners.manage",
  "partners.own",
  "productions.manage",
  "qalam.manage",
  "settings.manage",
  "tour.run",
]);

const rows = [...roleKeys]
  .sort((a, b) => roles[a].nameEn.localeCompare(roles[b].nameEn))
  .map((key) => {
    const role = roles[key];
    const twoStep =
      role.isCouncil || role.permissions.some((p) => PERSONAL.has(p));
    const permissions =
      role.permissions.length > 0
        ? [...role.permissions]
            .sort()
            .map((p) => `\`${p}\``)
            .join(", ")
        : "none";
    return `| ${role.nameEn} | \`${key}\` | ${role.defaultScope} | ${role.isCouncil ? "yes" : ""} | ${twoStep ? "yes" : ""} | ${permissions} |`;
  });

const text = `# Permissions

Generated by \`bun run permissions\` from \`apps/web/lib/rbac/roles.ts\`
(the mirror of the database's role bundles); do not edit by hand. The
Leadership Handbook (SAL-EXB-01) links here, and the Secretary checks who
holds what against it at the quarterly access review.

**Two-step:** the role needs two-step sign-in (the Council, the Elections
Committee, and from Sunday, November 22, 2026, every role that reaches
personal data). A passkey sign-in counts.

| Role | Key | Scope | Council | Two-step | Permissions |
|---|---|---|---|---|---|
${rows.join("\n")}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    console.error(
      "docs/platform/permissions.md is out of date: run `bun run permissions`."
    );
    process.exit(1);
  }
  console.log("Permissions table OK.");
} else {
  writeFileSync(OUT, text);
  console.log(`Permissions table: ${rows.length} roles.`);
}
